// Writes config.js and the WebUI's setting descriptions and on/off settings (src/ui/config/configDescriptions.js). Nobody edits either
// by hand: the settings come from the defineCheat rows in src/cheats/cheats/ (each row's `config` is
// cheatConfig[row.name]) and from the injector's own settings in src/modules/config/coreSettings.js.
//
//   node scripts/config-file.mjs     (npm run config:generate) rewrite both files
//
// scripts/cheats/config-file.test.mjs (part of npm run check) fails while the committed files differ from what
// this writes.
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import prettier from "prettier";
import { cheatFiles } from "../rollup.config.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const CONFIG_PATH = path.join(root, "config.js");
export const DESCRIPTIONS_PATH = path.join(root, "src", "ui", "config", "configDescriptions.js");

const CONFIG_HEADER = `// The default settings. Don't edit this file: it is generated (npm run config:generate) from the cheats in
// src/cheats/cheats/ and from src/modules/config/coreSettings.js, and an update replaces it.
// Put your own settings in config.custom.js; the WebUI's Config page saves them there.`;
const DESCRIPTIONS_HEADER = `// What each setting does, for the WebUI's Config page. Generated by npm run config:generate from the same
// sources as config.js; don't edit it.`;

/** A setting is `{ default, description }`, `{ example, description }` or `{ description }`; anything else is a group. */
const isSetting = (value) => "default" in value || "example" in value || "description" in value;

/** The settings: the core ones, then each cheat row's. */
export async function loadSettings() {
    // src/cheats is ES modules in a package without "type": "module"; Node would warn once per file.
    const emitWarning = process.emitWarning;
    process.emitWarning = (warning, ...rest) =>
        rest[0]?.code === "MODULE_TYPELESS_PACKAGE_JSON" ? undefined : emitWarning.call(process, warning, ...rest);
    // wide.js starts its autoboss timer on import; it must not keep Node running.
    const setInterval = globalThis.setInterval;
    globalThis.setInterval = (...args) => setInterval(...args).unref();
    for (const file of cheatFiles()) await import(pathToFileURL(path.join(root, "src", "cheats", "cheats", file)).href);
    globalThis.setInterval = setInterval;
    process.emitWarning = emitWarning;

    const { cheatRows } = await import(pathToFileURL(path.join(root, "src", "cheats", "core", "registration.js")).href);
    const core = createRequire(import.meta.url)("../src/modules/config/coreSettings.js");
    const cheatConfig = { ...core.cheatConfig };
    for (const row of cheatRows) {
        if (!row.config) continue;
        if (row.name in cheatConfig) throw new Error(`cheatConfig.${row.name} is declared twice`);
        cheatConfig[row.name] = row.config;
    }
    return { startupCheats: core.startupCheats, cheatConfig, injectorConfig: core.injectorConfig };
}

const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));
// Formula defaults like (t) => t / 4 stay functions: their source is written as is.
const literal = (value) => (typeof value === "function" ? value.toString() : JSON.stringify(value));
const comment = (description) => (description ? ` // ${description.replace(/\s+/g, " ")}` : "");
const hasValues = (tree) =>
    Object.values(tree).some((value) =>
        isSetting(value) ? "default" in value || "example" in value : hasValues(value)
    );

/** The object literal's body: each default, each example commented out, and the description behind it. */
function body(tree) {
    const lines = [];
    for (const [name, value] of Object.entries(tree)) {
        if (!isSetting(value)) {
            if (hasValues(value)) lines.push(`${key(name)}: {\n${body(value)}\n},`);
        } else if ("default" in value) {
            lines.push(`${key(name)}: ${literal(value.default)},${comment(value.description)}`);
        } else if ("example" in value) {
            const line = `${key(name)}: ${literal(value.example)},${comment(value.description)}`;
            lines.push(`// ${line.replace(/\n/g, "\n// ")}`);
        }
    }
    return lines.join("\n");
}

/** Every description, keyed by the setting's path ("cheatConfig.w1.anvil.productionspeed"). */
function descriptions(tree, prefix, out = []) {
    for (const [name, value] of Object.entries(tree)) {
        if (!isSetting(value)) descriptions(value, `${prefix}.${name}`, out);
        else if (value.description)
            out.push(`${JSON.stringify(`${prefix}.${name}`)}: ${JSON.stringify(value.description)},`);
    }
    return out;
}

/** Every on/off setting's on value (`on` in its row: what the game checks for), keyed like the descriptions. */
function switches(tree, prefix, out = []) {
    for (const [name, value] of Object.entries(tree)) {
        if (!isSetting(value)) switches(value, `${prefix}.${name}`, out);
        else if ("on" in value) out.push(`${JSON.stringify(`${prefix}.${name}`)}: ${JSON.stringify(value.on)},`);
    }
    return out;
}

const format = async (text, file) => prettier.format(text, { ...(await prettier.resolveConfig(file)), filepath: file });

/** What config.js and configDescriptions.js should contain. */
export async function generate() {
    const { startupCheats, cheatConfig, injectorConfig } = await loadSettings();
    const config = [
        CONFIG_HEADER,
        `exports.startupCheats = ${JSON.stringify(startupCheats)};`,
        `exports.cheatConfig = {\n${body(cheatConfig)}\n};`,
        `exports.injectorConfig = {\n${body(injectorConfig)}\n};`,
    ].join("\n\n");
    const lines = [...descriptions(cheatConfig, "cheatConfig"), ...descriptions(injectorConfig, "injectorConfig")];
    const described = [
        DESCRIPTIONS_HEADER,
        `export const configDescriptions = {\n${lines.join("\n")}\n};`,
        "// The on/off settings, with the value each holds when on. The WebUI shows them as switches.",
        `export const configSwitches = {\n${switches(cheatConfig, "cheatConfig").join("\n")}\n};`,
    ].join("\n");
    return {
        [CONFIG_PATH]: await format(config, CONFIG_PATH),
        [DESCRIPTIONS_PATH]: await format(described, DESCRIPTIONS_PATH),
    };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    for (const [file, text] of Object.entries(await generate())) {
        const changed = !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text;
        if (changed) fs.writeFileSync(file, text);
        console.log(`${changed ? "wrote" : "unchanged"} ${path.relative(root, file)}`);
    }
}
